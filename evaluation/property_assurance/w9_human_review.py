"""Fail-closed validation for the mandatory W9 human review gate.

The review artifact is intentionally not generated by this module. A human
reviewer must create it after inspecting outcome-blind packets; a model output,
placeholder, or status-only manifest cannot open the W9 denominator gate.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from evaluation.evidence_program.freeze import FreezeError, sha256

HUMAN_REVIEW_SCHEMA_VERSION = "govmut-w9-human-review.v1"
HUMAN_LABELS = frozenset({"NON_EQUIVALENT", "EQUIVALENT", "INVALID", "UNCERTAIN"})
FINAL_DISPOSITIONS = frozenset(
    {"included", "excluded_equivalent", "excluded_unexecutable", "unresolved"}
)


def _disposition_for_labels(labels: list[str]) -> str:
    """Apply the frozen rule to one candidate's human labels."""
    if len(set(labels)) == 1:
        return {
            "NON_EQUIVALENT": "included",
            "EQUIVALENT": "excluded_equivalent",
            "INVALID": "excluded_unexecutable",
        }.get(labels[0], "unresolved")
    return "unresolved"


def _load_json(path: Path, error: str) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise FreezeError(error) from exc
    if not isinstance(value, dict):
        raise FreezeError(error)
    return value


def _catalog_ids(catalog_path: Path) -> list[str]:
    catalog = _load_json(catalog_path, "govmut_w9_human_catalog_invalid")
    candidates = catalog.get("candidates")
    if not isinstance(candidates, list) or not candidates:
        raise FreezeError("govmut_w9_human_catalog_invalid")
    ids = [candidate.get("id") for candidate in candidates if isinstance(candidate, dict)]
    if len(ids) != len(candidates) or not all(isinstance(item, str) and item for item in ids):
        raise FreezeError("govmut_w9_human_catalog_invalid")
    if len(set(ids)) != len(ids):
        raise FreezeError("govmut_w9_human_catalog_duplicate_ids")
    return ids


def validate_human_review_gate(*, manifest_path: Path, catalog_path: Path) -> dict[str, Any]:
    """Validate a completed, outcome-blind human review before execution."""

    manifest = _load_json(manifest_path, "govmut_w9_human_manifest_invalid")
    gate = manifest.get("human_review")
    if not isinstance(gate, dict) or gate.get("status") != "completed":
        raise FreezeError("govmut_w9_human_review_gate_open")
    artifact_name = gate.get("artifact")
    digest = gate.get("results_sha256")
    if not isinstance(artifact_name, str) or not artifact_name.strip():
        raise FreezeError("govmut_w9_human_review_artifact_invalid")
    artifact = (manifest_path.parent / artifact_name).resolve()
    try:
        artifact.relative_to(manifest_path.parent.resolve())
    except ValueError as exc:
        raise FreezeError("govmut_w9_human_review_artifact_outside_manifest") from exc
    if not artifact.is_file():
        raise FreezeError("govmut_w9_human_review_artifact_missing")
    if not isinstance(digest, str) or sha256(artifact) != digest:
        raise FreezeError("govmut_w9_human_review_artifact_hash_mismatch")

    review = _load_json(artifact, "govmut_w9_human_review_artifact_invalid")
    if (
        review.get("schema_version") != HUMAN_REVIEW_SCHEMA_VERSION
        or review.get("status") != "completed"
        or review.get("review_mode") != "human_manual"
        or review.get("llm_calls") is not False
    ):
        raise FreezeError("govmut_w9_human_review_artifact_invalid")
    reviewers = review.get("reviewers")
    if not isinstance(reviewers, list) or not reviewers:
        raise FreezeError("govmut_w9_human_review_reviewers_invalid")
    reviewer_ids: list[str] = []
    for reviewer in reviewers:
        if not isinstance(reviewer, dict):
            raise FreezeError("govmut_w9_human_review_reviewer_invalid")
        required = ("reviewer_id", "background", "independence_declaration", "review_date")
        if not all(
            isinstance(reviewer.get(field), str) and reviewer[field].strip() for field in required
        ):
            raise FreezeError("govmut_w9_human_review_reviewer_invalid")
        reviewer_ids.append(reviewer["reviewer_id"])
    if len(set(reviewer_ids)) != len(reviewer_ids):
        raise FreezeError("govmut_w9_human_review_duplicate_reviewer")

    expected_ids = _catalog_ids(catalog_path)
    candidates = review.get("candidates")
    if not isinstance(candidates, list):
        raise FreezeError("govmut_w9_human_review_candidates_invalid")
    candidate_ids: list[str] = []
    for candidate in candidates:
        if not isinstance(candidate, dict):
            raise FreezeError("govmut_w9_human_review_candidate_invalid")
        case_id = candidate.get("case_id")
        packet_ref = candidate.get("packet_ref")
        dispositions = candidate.get("reviewer_dispositions")
        if (
            not isinstance(case_id, str)
            or not isinstance(packet_ref, str)
            or not packet_ref.strip()
            or not isinstance(dispositions, dict)
            or set(dispositions) != set(reviewer_ids)
            or candidate.get("final_disposition") not in FINAL_DISPOSITIONS
        ):
            raise FreezeError("govmut_w9_human_review_candidate_invalid")
        for reviewer_id, disposition in dispositions.items():
            if (
                not isinstance(disposition, dict)
                or disposition.get("label") not in HUMAN_LABELS
                or not isinstance(disposition.get("rationale"), str)
                or not disposition["rationale"].strip()
            ):
                raise FreezeError(f"govmut_w9_human_review_disposition_invalid:{reviewer_id}")
        expected_disposition = _disposition_for_labels(
            [dispositions[reviewer_id]["label"] for reviewer_id in reviewer_ids]
        )
        if candidate["final_disposition"] != expected_disposition:
            raise FreezeError("govmut_w9_human_review_final_disposition_invalid")
        candidate_ids.append(case_id)
    if candidate_ids != expected_ids or len(set(candidate_ids)) != len(candidate_ids):
        raise FreezeError("govmut_w9_human_review_candidate_coverage_invalid")
    if not isinstance(review.get("completed_at"), str) or not review["completed_at"].strip():
        raise FreezeError("govmut_w9_human_review_completion_date_invalid")
    return review

"""IFIP_SEC-X07_replay_generator — deterministic replay-attack sequence builder.

Purpose
-------
Phase P02 task ``IFIP_SEC-X07_replay_generator`` of the IFIP SEC 2027 study
"Replay-Closed Authorization Across Purpose, Delegation, and AI Proposal
Lineage" (research/venue2027/VENUES/ifip_sec/RESEARCH_BLUEPRINT.md, RQ1).
:func:`generate_replays` turns legitimate base requests into a deterministic,
PHI-free list of replay ATTACKS across the four registered IFIP_SEC families:

- ``cross_purpose`` (CASE-02): the ``purpose`` field is mutated away from the
  granted consent purpose (violates purpose-domain separation),
- ``delegation_replay``: the ``nonce_state`` is mutated to
  ``consumed_by_delegate`` — the delegate consumed the consume-once nonce, so
  the delegated receipt is no longer presentable (violates the consume-once
  invariant),
- ``lineage_splice``: the ``consent_epoch`` is mutated to an epoch that no
  longer derives from ``parent_consent_epoch`` (violates the
  delegation-ancestry/provenance binding),
- ``nonce_replay``: the ``nonce_state`` is mutated to ``consumed`` — the
  receipt's nonce is already consumed and its verbatim presentation (same
  nonce) is submitted again (violates the consume-once invariant).

Each mutation changes exactly the family's declared primary field
(:data:`MUTATED_FIELD`); the mutated copy is the *attack record* in the same
ground-truth signal convention as the venue dataset
(``evaluation.venue2027.ifip_sec.generate_dataset``). Every
:class:`ReplayAttack` records the mutated field, the original (legitimate)
request, the violated invariant, and the expected independent-oracle verdict
(``REJECT`` — every attack family adjudicates to REJECT under the frozen
``IFIP_REFERENCE_RULES`` of
:mod:`evaluation.venue2027.ifip_sec.independent_oracle`; ``nonce_replay``
shares the ``delegation_replay`` rule-table row because both break the same
consume-once invariant). For every attack a paired legitimate operation
(``fresh_accept`` shape, expected ``ADMIT``) is derivable via
:func:`legitimate_control`. Cases carry ``family``/``case_id`` labels so the
independent oracle can be exercised directly; this module never imports the
oracle or any candidate/baseline module (oracle independence preserved).

Allowed input
-------------
``seed`` (int), ``base_cases`` (JSON-serializable sequence of legitimate
request mappings; defaults to the deterministic synthetic requests of
:func:`default_base_cases`), ``n`` (positive int) for
:func:`generate_replays`; seed and count for :func:`default_base_cases`. No
network, no database, no hidden clock or randomness beyond the seed; no
production secret or patient-data access. All inputs and outputs are
JSON-serializable.

Failure semantics
-----------------
Fail closed with stable ``reason_code`` via :class:`ReplayGeneratorError`:
``INVALID_SEED`` (non-int seed), ``INVALID_N`` (non-positive n),
``INVALID_BASE_CASE`` (base case is not a well-formed request mapping),
``UNKNOWN_FAMILY`` (an unregistered family was requested or smuggled in a
base case), ``UNMUTATED_REQUEST`` (the family's primary-field mutation would
be a no-op on the base case, i.e. no attack can be formed — an already
attack-shaped or non-mutatable request is never silently returned as an
attack), ``PHI_FIELD_PRESENT`` (a field name resembles PHI/PII). Never
silently returns a non-attack, silently drops a family, or masks a malformed
base case as a safe rejection.

Version
-------
``REPLAY_GENERATOR_VERSION = "1.0.0"``
"""

from __future__ import annotations

import dataclasses
import hashlib
import json
import re
from collections.abc import Mapping, Sequence
from typing import Any, Final

REPLAY_GENERATOR_VERSION: Final[str] = "1.0.0"
REPLAY_SCHEMA_VERSION: Final[str] = "clara.venue2027.ifip_sec.replay_attack.v1"
VENUE: Final[str] = "ifip_sec"

#: Attack families generated by :func:`generate_replays`. ``nonce_replay`` is
#: the X07-specific duplicate-presentation variant (consume-once again); the
#: other three correspond to the dataset generator families
#: (``cross_purpose_replay`` / ``delegation_replay`` / ``lineage_splice``).
ATTACK_FAMILIES: Final[tuple[str, ...]] = (
    "cross_purpose",
    "delegation_replay",
    "lineage_splice",
    "nonce_replay",
)

#: All families (legitimate control + attacks) recognized in base cases.
KNOWN_FAMILIES: Final[tuple[str, ...]] = ("fresh_accept", *ATTACK_FAMILIES)

#: Invariant violated per attack family (single source of truth for the
#: ``violated_invariant`` field and the test assertions).
VIOLATED_INVARIANTS: Final[dict[str, str]] = {
    "cross_purpose": "purpose_domain_separation",
    "delegation_replay": "consume_once_nonce",
    "lineage_splice": "delegation_ancestry_binding",
    "nonce_replay": "consume_once_nonce",
}

#: Expected independent-oracle verdict for each family. Every attack violates
#: a frozen invariant, so the expected verdict is always REJECT.
EXPECTED_VERDICTS: Final[dict[str, str]] = {f: "REJECT" for f in ATTACK_FAMILIES}

#: Frozen independent-oracle rule-table family
#: (``independent_oracle.IFIP_REFERENCE_RULES``) that each attack family
#: adjudicates under. ``nonce_replay`` has no dedicated rule-table row; it
#: maps onto ``delegation_replay`` because both violate consume-once.
ORACLE_FAMILY_FOR_ATTACK: Final[dict[str, str]] = {
    "cross_purpose": "cross_purpose_replay",
    "delegation_replay": "delegation_replay",
    "lineage_splice": "lineage_splice",
    "nonce_replay": "delegation_replay",
}

#: Primary field mutated per attack family (exactly one field changes).
MUTATED_FIELD: Final[dict[str, str]] = {
    "cross_purpose": "purpose",
    "delegation_replay": "nonce_state",
    "lineage_splice": "consent_epoch",
    "nonce_replay": "nonce_state",
}

_PURPOSES: Final[tuple[str, ...]] = (
    "self_care",
    "clinical_review",
    "billing_audit",
    "research_export",
)
_OPERATIONS: Final[tuple[str, ...]] = (
    "proposal.dispatch",
    "proposal.verify",
    "receipt.consume",
    "lineage.append",
)
_EPOCH_COUNT: Final[int] = 4
_NONCE_STATES: Final[tuple[str, ...]] = ("fresh", "consumed", "consumed_by_delegate")
_EPOCH_PATTERN: Final[re.Pattern[str]] = re.compile(r"^consent-\d+$")

_PHI_FIELD_MARKERS: Final[tuple[str, ...]] = (
    "name",
    "email",
    "phone",
    "address",
    "national_id",
    "passport",
    "mrn",
    "insurance_id",
    "dob",
    "date_of_birth",
)

_REQUIRED_REQUEST_FIELDS: Final[tuple[str, ...]] = (
    "tenant_id",
    "actor_id",
    "purpose",
    "operation",
    "consent_epoch",
    "parent_consent_epoch",
    "delegation_depth",
    "nonce",
    "nonce_state",
    "replay_flag",
)


class ReplayGeneratorError(ValueError):
    """Stable-reason-code error; never an unhandled exception counted as safe."""

    def __init__(self, reason_code: str, detail: str) -> None:
        super().__init__(f"{reason_code}: {detail}")
        self.reason_code = reason_code
        self.detail = detail


@dataclasses.dataclass(frozen=True)
class ReplayAttack:
    """One mutated replay attack derived from a legitimate base request.

    JSON-serializable via :meth:`to_dict`; ``original_request`` is carried
    verbatim so downstream adjudication can compare original vs. attack.
    """

    attack_id: str
    family: str
    mutated_field: str
    original_request: dict[str, Any]
    mutated_request: dict[str, Any]
    violated_invariant: str
    expected_oracle_verdict: str
    oracle_family: str
    schema_version: str = REPLAY_SCHEMA_VERSION
    generator_version: str = REPLAY_GENERATOR_VERSION

    def to_dict(self) -> dict[str, Any]:
        return {
            "attack_id": self.attack_id,
            "family": self.family,
            "mutated_field": self.mutated_field,
            "original_request": dict(self.original_request),
            "mutated_request": dict(self.mutated_request),
            "violated_invariant": self.violated_invariant,
            "expected_oracle_verdict": self.expected_oracle_verdict,
            "oracle_family": self.oracle_family,
            "schema_version": self.schema_version,
            "generator_version": self.generator_version,
        }


def _determinant(seed: int, idx: int) -> int:
    """Same arithmetic anchor as the dataset kernel/extension layers."""

    return (seed * 7919 + idx * 104729) % 100003


def _check_no_phi(request: Mapping[str, Any], source: str) -> None:
    for key in request:
        lowered = key.lower()
        if any(marker in lowered for marker in _PHI_FIELD_MARKERS):
            raise ReplayGeneratorError(
                "PHI_FIELD_PRESENT",
                f"{source}: field {key!r} looks like PHI/PII; only synthetic identifiers allowed",
            )


def _validate_request(request: Mapping[str, Any], source: str) -> None:
    if not isinstance(request, Mapping):
        raise ReplayGeneratorError(
            "INVALID_BASE_CASE",
            f"{source}: request must be a mapping, got {type(request).__name__}",
        )
    _check_no_phi(request, source)
    missing = [f for f in _REQUIRED_REQUEST_FIELDS if f not in request]
    if missing:
        raise ReplayGeneratorError(
            "INVALID_BASE_CASE", f"{source}: missing required field(s) {missing}"
        )
    family = request.get("family", "fresh_accept")
    if family not in KNOWN_FAMILIES:
        raise ReplayGeneratorError(
            "UNKNOWN_FAMILY", f"{source}: family {family!r} is not registered for {VENUE}"
        )
    depth = request.get("delegation_depth")
    if not isinstance(depth, int) or isinstance(depth, bool) or depth < 0:
        raise ReplayGeneratorError(
            "INVALID_BASE_CASE", f"{source}: delegation_depth must be a non-negative int"
        )
    if not isinstance(request.get("replay_flag"), bool):
        raise ReplayGeneratorError("INVALID_BASE_CASE", f"{source}: replay_flag must be a bool")
    if request.get("nonce_state") not in _NONCE_STATES:
        raise ReplayGeneratorError(
            "INVALID_BASE_CASE", f"{source}: nonce_state must be one of {_NONCE_STATES}"
        )
    for field in ("consent_epoch", "parent_consent_epoch"):
        value = request.get(field)
        if not isinstance(value, str) or not _EPOCH_PATTERN.match(value):
            raise ReplayGeneratorError(
                "INVALID_BASE_CASE",
                f"{source}: {field} must match 'consent-<int>', got {value!r}",
            )


def _request_digest(payload: Mapping[str, Any]) -> str:
    return hashlib.sha256(
        json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()[:12]


def default_base_cases(seed: int, n: int = 4) -> list[dict[str, Any]]:
    """Deterministic, PHI-free legitimate base requests (fresh_accept shape).

    Each returned request is a legitimate governed operation: purpose equals
    granted purpose, the claimed consent epoch matches its parent, depth >= 1,
    fresh nonce, no replay flag. ``n`` controls how many distinct base
    requests are produced (round-robin over purpose/operation/epoch slots,
    deterministically mixed by ``seed``).
    """

    if not isinstance(seed, int) or isinstance(seed, bool):
        raise ReplayGeneratorError("INVALID_SEED", "seed must be an int")
    if not isinstance(n, int) or isinstance(n, bool) or n <= 0:
        raise ReplayGeneratorError("INVALID_N", "n must be a positive int")
    cases: list[dict[str, Any]] = []
    for idx in range(n):
        det = _determinant(seed, idx)
        granted = _PURPOSES[det % len(_PURPOSES)]
        epoch = det % _EPOCH_COUNT
        request: dict[str, Any] = {
            "family": "fresh_accept",
            "request_id": f"req-{seed}-{idx:05d}",
            "tenant_id": f"synthetic-tenant-{det % 3}",
            "actor_id": f"synthetic-actor-{det % 7}",
            "purpose": granted,
            "granted_purpose": granted,
            "operation": _OPERATIONS[det % len(_OPERATIONS)],
            "consent_epoch": f"consent-{epoch}",
            "parent_consent_epoch": f"consent-{epoch}",
            "delegation_depth": 1 + det % 3,
            "nonce": f"nonce-{_request_digest({'seed': seed, 'idx': idx})}-{det % 10000:04d}",
            "nonce_state": "fresh",
            "replay_flag": False,
        }
        _validate_request(request, f"default_base_cases[{idx}]")
        cases.append(request)
    return cases


def _mutate(family: str, request: Mapping[str, Any]) -> dict[str, Any]:
    """Return the mutated copy of ``request`` for ``family``.

    Pure function of ``(family, request)``: exactly the family's primary
    field changes and the result is the attack record in the dataset
    ground-truth signal convention. Raises ``UNMUTATED_REQUEST`` when the
    primary-field mutation would be a no-op (no attack can be formed).
    """

    mutated = dict(request)
    if family == "cross_purpose":
        granted = mutated.get("granted_purpose", mutated["purpose"])
        current = mutated["purpose"]
        candidates = [p for p in _PURPOSES if p != granted and p != current]
        if not candidates:
            # Only possible when len(_PURPOSES) < 3; defensive, never hit today.
            raise ReplayGeneratorError(
                "UNMUTATED_REQUEST",
                f"family {family!r}: no alternative purpose available; not an attack",
            )
        mutated["purpose"] = candidates[0]
    elif family == "delegation_replay":
        if mutated["nonce_state"] == "consumed_by_delegate":
            raise ReplayGeneratorError(
                "UNMUTATED_REQUEST",
                f"family {family!r}: nonce_state already records "
                "consumed_by_delegate; not an attack",
            )
        mutated["nonce_state"] = "consumed_by_delegate"
    elif family == "lineage_splice":
        parent = mutated["parent_consent_epoch"]
        parent_num = int(parent.rsplit("-", 1)[-1])
        target = f"consent-{(parent_num + 1) % _EPOCH_COUNT}"
        if target == mutated["consent_epoch"]:
            target = f"consent-{(parent_num + 2) % _EPOCH_COUNT}"
        mutated["consent_epoch"] = target
    elif family == "nonce_replay":
        if mutated["nonce_state"] == "consumed":
            raise ReplayGeneratorError(
                "UNMUTATED_REQUEST",
                f"family {family!r}: nonce_state already records consumed; not an attack",
            )
        mutated["nonce_state"] = "consumed"
    else:
        raise ReplayGeneratorError(
            "UNKNOWN_FAMILY", f"family {family!r} is not registered for {VENUE}"
        )
    return mutated


def _verify_mutation(family: str, original: Mapping[str, Any], mutated: Mapping[str, Any]) -> None:
    """Fail closed when a mutation is a no-op (the result would not be an attack)."""

    field = MUTATED_FIELD[family]
    if original == mutated:
        raise ReplayGeneratorError(
            "UNMUTATED_REQUEST",
            f"family {family!r}: mutated request equals original request; not an attack",
        )
    if original.get(field) == mutated.get(field):
        raise ReplayGeneratorError(
            "UNMUTATED_REQUEST",
            f"family {family!r}: mutated field {field!r} unchanged; not an attack",
        )


def generate_replays(
    seed: int,
    base_cases: Sequence[Mapping[str, Any]] | None = None,
    n: int = 8,
) -> list[ReplayAttack]:
    """Generate deterministic replay attacks across all four attack families.

    ``base_cases`` defaults to :func:`default_base_cases(seed, n)`; otherwise
    each provided request is validated and mutated once per family cycle.
    Attacks are distributed round-robin over :data:`ATTACK_FAMILIES` so every
    family is always represented (``n >= 4`` yields at least one of each),
    and ordering is a pure function of ``(seed, base_cases, n)`` — the same
    inputs always yield identical output.

    Raises :class:`ReplayGeneratorError` with a stable ``reason_code`` on any
    invalid input; never returns a partially built list.
    """

    if not isinstance(seed, int) or isinstance(seed, bool):
        raise ReplayGeneratorError("INVALID_SEED", "seed must be an int")
    if not isinstance(n, int) or isinstance(n, bool) or n <= 0:
        raise ReplayGeneratorError("INVALID_N", "n must be a positive int")
    if base_cases is None:
        cases = default_base_cases(seed, n=n)
    else:
        cases = []
        for i, request in enumerate(base_cases):
            source = f"base_cases[{i}]"
            _validate_request(request, source)
            cases.append(dict(request))

    attacks: list[ReplayAttack] = []
    for i in range(n):
        family = ATTACK_FAMILIES[i % len(ATTACK_FAMILIES)]
        original = cases[i % len(cases)]
        mutated = _mutate(family, original)
        _verify_mutation(family, original, mutated)
        attacks.append(
            ReplayAttack(
                attack_id=(
                    f"attack-{_request_digest({'family': family, 'seed': seed, 'i': i})}-{family}"
                ),
                family=family,
                mutated_field=MUTATED_FIELD[family],
                original_request=dict(original),
                mutated_request=mutated,
                violated_invariant=VIOLATED_INVARIANTS[family],
                expected_oracle_verdict=EXPECTED_VERDICTS[family],
                oracle_family=ORACLE_FAMILY_FOR_ATTACK[family],
            )
        )
    return attacks


def legitimate_control(attack: ReplayAttack) -> dict[str, Any]:
    """Return the paired legitimate operation for one attack (expected ADMIT).

    The control is the attack's ``original_request`` normalized to the
    legitimate ``fresh_accept`` shape: purpose matches the granted purpose,
    the nonce is fresh, no replay flag and the claimed epoch matches its
    parent. Paired with the attack it shares actor/tenant/operation so
    downstream comparison isolates the mutation as the only difference.
    """

    original = dict(attack.original_request)
    granted = original.get("granted_purpose", original["purpose"])
    control = {
        **original,
        "family": "fresh_accept",
        "purpose": granted,
        "granted_purpose": granted,
        "parent_consent_epoch": original["consent_epoch"],
        "nonce_state": "fresh",
        "replay_flag": False,
    }
    _validate_request(control, f"legitimate_control[{attack.attack_id}]")
    return control
